const inventory = [];
let room = "деревня";

let wizardMet = false // встреча с волшебником
let wizardTrust = 1; //доверие волшебника
let armorOffered = false; // доспехи предложены
let armorGifted = false // доспехи подарены

function showInventory() {
    if (inventory.length === 0) {
        alert("Рюкзак пуст.");
    } else {
        alert("В рюкзаке: " + inventory.join(", "));
    }
}

function askAboutArmor() {
    if (armorGifted) {
        alert("Доспехи я тебе уже отдал. Береги их в бою.");
        return;
    }
    if (armorOffered && !armorGifted) {
        alert("Ты отказался от доспехов. Ты полный дурак.");
        return;
    }

    armorOffered = true;

    const reply = prompt(
        "Выслушай предостережение, рыцарь.\n" +
        "Дракон дышит пламенем, от которого плавится сталь.\n" +
        "Тебе нужны огнеупорные доспехи.\n\n" +
        "1 — Где мне их взять?\n" +
        "2 — Доспехи для трусов\n" +
        "3 — У меня есть свой план"
    );

    if (reply === null) return;

    if (reply === "1") {
        wizardTrust = wizardTrust + 1;
        alert("Возьми доспехи, они спасут тебе жизнь.");
        if (!inventory.includes("огнеупорные доспехи")) {
            inventory.push("огнеупорные доспехи");
        }
        armorGifted = true;
    } else if (reply === "2") {
        wizardTrust = wizardTrust - 2;
        alert("Гордость — плохой советчик.\nДракон не прощает ошибок. Ты умрёшь.");
    } else if (reply === "3") {
        if (wizardTrust >= 2) {
            alert("Ты доказал свою мудрость. Доспехи не помешают, возьми их.");
            if (!inventory.includes("огнеупорные доспехи")) {
                inventory.push("огнеупорные доспехи");
            }
            armorGifted = true;
        } else {
            alert("Поступай по-своему.\nНо помни: без доспехов бой будет коротким.");
        }
    }
}

function talkToWizard() {
    if (!wizardMet) {
        const intro = prompt(
            "Старый волшебник\n" +
            "Приветствую, рыцарь. Зачем ты пришёл?\n\n" +
            "1 — Спасти принцессу\n" +
            "2 — Ищу подвигов и славы\n" +
            "3 — Хочу узнать о драконе\n" +
            "4 — Уйти"
        );

        if (intro === null || intro === "4") return;

        if (intro === "1") {
            alert("Благородное дело. Я помогу тебе словом и делом.");
            wizardTrust = 2;
        } else if (intro === "2") {
            alert("Слава губит многих. Но совет я всё же дам.");
            wizardTrust = 1;
        } else if (intro === "3") {
            alert("Значит, слух о драконе привёл. Слушай внимательно.");
            wizardTrust = 1;
        }

        wizardMet = true;
    }

    while (true) {
        const choice = prompt(
            "Старый волшебник\n" +
            "1 — Чего мне не хватает?\n" +
            "2 — Расскажи о драконе\n" +
            "3 — Расскажи о магическом мече\n" +
            "4 — Дай мне предостережение\n" +
            "5 — Проверить рюкзак\n" +
            "6 — Прощай"
        );

        if (choice === null || choice === "6") return;

        if (choice === "1") {
            // Волшебник замечает золото и узнаёт чеканку
            if (inventory.includes("золотые монеты")) {
                alert(
                    "Волшебник вдруг замечает что-то в твоём рюкзаке.\n" +
                    "Он подходит ближе, щурится...\n\n" +
                    "«Позволь взглянуть... Это же монеты из старой казны!\n" +
                    "Я узнаю чеканку. Где ты их нашёл?»\n\n" +
                    "Он долго вертит монету в пальцах.\n\n" +
                    "Тысячу лет назад дракон разорил казну. Все монеты\n" +
                    "он унёс к себе. Но часть осела в храмах — кто-то\n" +
                    "успел спрятать. Он ищет их до сих пор.\n" +
                    "У дракона очень хорошая память. И нюх на своё добро.»\n\n" +
                    "Волшебник протягивает руку:\n" +
                    "«Хочешь совет? Оставь их у меня. В моём сундуке\n" +
                    "дракон их не почует."
                );

                const giveGold = confirm("Отдать монеты волшебнику?");

                if (giveGold === true) {
                    const goldIndex = inventory.indexOf("золотые монеты");
                    if (goldIndex !== -1) {
                        inventory.splice(goldIndex, 1);
                    }

                alert("Волшебник убирает золото в сундук и запирает на ключ.");
                } else {
                    alert(
                        "Волшебник качает головой:\n" +
                        "Твоё дело, рыцарь. Но я бы не носил это к дракону."
                    );
                }
            }

            const missing = [];

            if (!inventory.includes("ключ")) {
                missing.push("ключ — в моём сундуке");
            }
            if (!inventory.includes("магический меч")) {
                missing.push("магический меч — в оружейной");
            }
            if (!inventory.includes("магическая трава")) {
                missing.push("магическая трава — в зачарованном лесу");
            }
            if (!inventory.includes("защитный амулет")) {
                missing.push("защитный амулет — в древнем храме");
            }
            if (!inventory.includes("огнеупорные доспехи")) {
                if (armorOffered && !armorGifted) {
                    missing.push("огнеупорные доспехи — ты уже отказался, глупец");
                } else if (!armorOffered) {
                    missing.push("огнеупорные доспехи — спроси меня о предостережении");
                }
            }

            if (missing.length === 0) {
                alert("Всё при тебе. Иди к дракону и не оглядывайся.");
            } else {
                alert("Тебе не хватает:\n" + missing.join("\n"));
            }
        } else if (choice === "2") {
            alert(
                "Дракон древний. Обычная сталь его не берёт.\n" +
                "Он дышит огнём, от которого плавится железо.\n\n" +
                "И память у него... завидная. Он помнит каждую вещь,\n" +
                "что когда-либо лежала в его пещере. Каждую монету.\n" +
                "Говорят, он и сейчас пересчитывает золото из старой казны,\n" +
                "которую разорил тысячу лет назад."
            );
            if (!armorOffered) {
                askAboutArmor();
            }
        } else if (choice === "3") {
            alert(
                "Магический меч выкован в древности из осколка звезды.\n" +
                "Он единственный способен ранить дракона.\n" +
                "Без него бой — верная смерть."
            );
        } else if (choice === "4") {
            askAboutArmor();
        } else if (choice === "5") {
            showInventory();
        } else {
            alert("Волшебник не понял.");
        }
    }
}

